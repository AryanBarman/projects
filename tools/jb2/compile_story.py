"""COMPILE a story:   python compile_story.py <id>      reads stories/<id>.story.json and writes the three build inputs  <id>_scene.js  <id>_keys.js  cfg_<id>.json
So a video is ONE data file (docs/STORY_SPEC.md). Automatic: captions come from the SRT in the audio folder, the ledger text is cut from the SRT per beat, models are found from the recipes used,
cues/punches default to one per beat start. check_short.py runs this for you when a story file exists."""
import sys, re, json, pathlib
H = pathlib.Path(__file__).resolve().parent; P = H.parent.parent
pid = sys.argv[1]; S = json.load(open(H / 'stories' / (pid + '.story.json'), encoding='utf8'))
MODEL_FILES = {'earth': 'Planet-B7xd3SZq0z', 'connector': 'Connector', 'dish': 'Roof_Radar', 'rover': 'Rover'}
NEEDS = {'SetLaunch': [], 'SetOrbit': ['earth', 'connector', 'dish'], 'Station': ['connector', 'dish'], 'SetRepo': ['rover']}
txt = json.dumps(S); models = {m for k, v in NEEDS.items() if '"%s"' % k in txt for m in v} | {m for m in MODEL_FILES if '"Model", "%s"' % m in txt}
audio = S.get('audio', pid); adir = S.get('audio_dir', 'shorts2/audio')
cues = []
srt = P / adir / (audio + '.srt')
if srt.exists():
    tsec = lambda x: (lambda h, m, r: int(h) * 3600 + int(m) * 60 + int(r.split(',')[0]) + int(r.split(',')[1]) / 1000)(*x.split(':'))
    for b in re.split(r'\n\s*\n', srt.read_text(encoding='utf8').replace('\r', '').strip()):
        L = b.split('\n')
        if len(L) >= 3: a, c = L[1].split(' --> '); cues.append((tsec(a), tsec(c), re.sub(r'(\w) -(\w)', r'\1-\2', ' '.join(L[2:]).strip())))
dur = S.get('dur') or round(cues[-1][1] + 0.2, 2)
sents, cur = [], None
for a, z, tx in cues:      # ledger rows = spoken SENTENCES (the camera check needs the real line ends)
    cur = [a, z, tx] if cur is None else [cur[0], z, cur[2] + ' ' + tx]
    if re.search(r'[.?!]["”]?$', tx.strip()): sents.append(cur); cur = None
if cur: sents.append(cur)
ledger = [['%.2f-%.2f' % (a, z), tx, 'scripted narration (unverified)', 'Story ' + pid, ''] for a, z, tx in sents] or [['%.2f-%.2f' % (b['t'][0], b['t'][1]), b.get('name', ''), '', 'Story ' + pid, ''] for b in S['beats']]
events = []      # impact times, for the camera check (a push/pull should end near one)
for b in S['beats']:
    for d in b.get('do', []):
        e = d['do'] if isinstance(d, dict) else d; n = e[0]; num = lambda v: v if isinstance(v, (int, float)) else None
        if n in ('Counter', 'Doc'): events.append(num(e[1].get('t0')))
        elif n == 'Band': events.append(num(e[2])) 
        elif n == 'RedX': events.append(num(e[-1]))
        elif n == 'SetLock': events.append(num(e[3]))
        elif n == 'SetLaunch': events.append(num(e[3]))
events = sorted({x for x in events if x})
cfg = {'assets': True, 'dmin': 20, 'dmax': 42, 'portrait': True, 'clean': True, 'stick': True, 'audio_dir': adir, 'audio': audio, 'out': S.get('out', pid + '.html'), 'out_dir': S.get('out_dir', 'shorts2'),
       'title': S.get('title', pid), 'dur': dur, 'rail': [0.0] + [b['t'][0] for b in S['beats'][1:]] + [dur], 'stn': [[1000000000, 0]], 'layout': [[0, 0]], 'sets': ['plaza'], 'fixes': S.get('fixes', {}), 'keycol': S.get('keycol', {}),
       'mood': S.get('mood', [[0, 'day']]), 'faces': [], 'dress': [], 'models': {m: 'assets3d/quaternius_ultimate_space_kit/glb/%s.glb' % MODEL_FILES[m] for m in sorted(models)},
       'punch': S.get('punch') or [[b['t'][0] + 0.05, 4, 0.05, 0.12] for b in S['beats']], 'ledger': ledger, 'events': events, 'cues': S.get('cues') or [[round(b['t'][0] + (1.3 if i else 0.0), 2), 'stamp_impact', b.get('name', '')] for i, b in enumerate(S['beats'])]}
SFXMAP = {'stamp_impact': ('stamp', -2), 'mega_boom': ('impact', 0), 'laser_trace': ('draw', -3), 'swell_boom': ('riser', -3), 'click': ('click', -1), 'pop': ('pop', -2), 'whoosh': ('whoosh', -4), 'ding': ('ding', -3), 'lock': ('lock', -2)}
sfx = S.get('sfx')
if sfx is None:      # sound effects: the cues (mapped to the synthesised library) + a whoosh at the start of every whip; sparse and quiet by design (docs/VIDEO_EXPORT.md)
    sfx = [{'t': c[0], 'sfx': SFXMAP.get(c[1], (c[1], -4))[0], 'db': SFXMAP.get(c[1], (c[1], -4))[1]} for c in cfg['cues']]
    sfx += [{'t': round(k[7] if len(k) > 7 and k[7] is not None else k[0] - 0.5, 2), 'sfx': 'whoosh', 'db': -4} for k in S['cam'] if len(k) > 6 and k[6] == 'whip']
cfg['sfx'] = sorted(sfx, key=lambda e: e['t'])
cfg['caption_style'] = S.get('caption_style', 'line')
cfg.update(S.get('cfg', {})); (H / ('cfg_%s.json' % pid)).write_text(json.dumps(cfg, indent=1, ensure_ascii=False), encoding='utf8')
js = lambda v: 'undefined' if v is None else ("'%s'" % v if isinstance(v, str) else json.dumps(v))
keys = ['  // generated by compile_story.py from stories/%s.story.json - do not edit' % pid] + ['  K(%s);' % ', '.join(js(v) for v in (k + [None] * 0)[:9]) for k in S['cam']]
(H / (pid + '_keys.js')).write_text('\n'.join(keys) + '\n', encoding='utf8')
hk = S.get('hook'); heads = '[[%s, %s, %s, %s, PAL.%s]]' % (hk['t'][0], hk['t'][1], json.dumps(hk['text']), json.dumps(hk.get('sub', '')), hk.get('accent', 'coral')) if hk else '[]'
story = {k: S[k] for k in ('beats', 'tracks') if k in S}
scene = """  // generated by compile_story.py from stories/%s.story.json - do not edit
  const HEADS = %s;
  const SPEC = %s;
  function renderShots(t) {
    const cv = evalCam(t);
    Cam3D.set([cv[0], cv[1], cv[2]], [cv[3], cv[4], cv[5]], cv[6], 0.01 * Math.sin(t * 0.6));
    GROUND = []; ITEMS = []; OVER = [];
    Story.run(t, SPEC);
    drawBG(0.05);
    GROUND.forEach(fn => fn());
    ITEMS.sort((a, b) => b.z - a.z).forEach(it => it.fn());
    OVER.forEach(fn => fn());
    HEADS.forEach(h => { const a = env(t, h[0], h[1], 0.001, 0.3); if (a > 0.01) drawHeadline(h[2], h[3], a, h[4], t, h[0]); });
  }
""" % (pid, heads, json.dumps(story, ensure_ascii=False, separators=(',', ':')))
(H / (pid + '_scene.js')).write_text(scene, encoding='utf8')
print('compiled %s: %d beats, %d camera keys, models %s' % (pid, len(S['beats']), len(S['cam']), sorted(models) or '-'))
